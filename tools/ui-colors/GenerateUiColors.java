import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * Turns a UiColorsDump table into a Kotlin file holding one UiTheme: the "#theme" line gives its id, name,
 * isDark and editor scheme; the "key<TAB>AARRGGBB" and "*<TAB>suffix<TAB>AARRGGBB" lines its colors.
 * Run: java GenerateUiColors.java <table.tsv> <Out.kt> <client build> <Kotlin val name>
 */
public final class GenerateUiColors {
  /** Kotlin keeps a string constant in the class file's constant pool, which holds at most 65535 bytes. */
  private static final int PART_BYTES = 30_000;

  public static void main(final String[] arguments) throws Exception {
    if (arguments.length != 4) {
      throw new IllegalArgumentException("Usage: java GenerateUiColors.java <table.tsv> <Out.kt> <client build> <Kotlin val name>");
    }
    final List<String> lines = Files.readAllLines(Path.of(arguments[0]));
    if (lines.isEmpty() || !lines.get(0).startsWith("#theme\t")) {
      throw new IllegalArgumentException("No #theme line first in " + arguments[0]);
    }
    final String[] theme = lines.get(0).split("\t");
    if (theme.length != 5) throw new IllegalArgumentException("Not a #theme line: " + lines.get(0));
    final List<String> colors = lines.subList(1, lines.size());
    for (final String line : lines) {
      if (line.contains("$") || line.contains("\"")) throw new IllegalArgumentException("Can't go in a Kotlin string: " + line);
    }
    final List<String> parts = new ArrayList<>();
    StringBuilder part = new StringBuilder();
    for (final String line : colors) {
      if (part.length() + line.length() + 1 > PART_BYTES) {
        parts.add(part.toString());
        part = new StringBuilder();
      }
      part.append(line).append('\n');
    }
    parts.add(part.toString());

    final String valName = arguments[3];
    final StringBuilder kotlin = new StringBuilder();
    kotlin.append("// Generated by tools/ui-colors/GenerateUiColors.java from JetBrains Client ")
        .append(arguments[2]).append("'s UIManager with ").append(theme[2]).append(". Don't edit; regenerate (docs/lux-protocol.md).\n");
    kotlin.append("package io.github.safeuq.ideate.client.ui.theme\n\n");
    kotlin.append("internal val ").append(valName).append(" =\n  UiTheme(\n")
        .append("    id = \"").append(theme[1]).append("\",\n")
        .append("    name = \"").append(theme[2]).append("\",\n")
        .append("    isDark = ").append(Boolean.parseBoolean(theme[3])).append(",\n")
        .append("    editorSchemeId = \"").append(theme[4]).append("\",\n")
        .append("    colorTable = listOf(");
    for (int index = 0; index < parts.size(); index++) {
      kotlin.append(index == 0 ? "" : ", ").append(valName).append("_PART_").append(index + 1);
    }
    kotlin.append("),\n  )\n");
    for (int index = 0; index < parts.size(); index++) {
      kotlin.append("\nprivate const val ").append(valName).append("_PART_").append(index + 1).append(" =\n  \"\"\"")
          .append(parts.get(index)).append("\"\"\"\n");
    }
    Files.writeString(Path.of(arguments[1]), kotlin.toString());
  }
}
