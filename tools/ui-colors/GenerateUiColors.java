import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * Turns a UiColorsDump table ("key<TAB>AARRGGBB" and "*<TAB>suffix<TAB>AARRGGBB" lines) into
 * IslandsDarkUiColors.kt. Run: java GenerateUiColors.java <table.tsv> <IslandsDarkUiColors.kt> <client build>
 */
public final class GenerateUiColors {
  /** Kotlin keeps a string constant in the class file's constant pool, which holds at most 65535 bytes. */
  private static final int PART_BYTES = 30_000;

  public static void main(final String[] arguments) throws Exception {
    if (arguments.length != 3) {
      throw new IllegalArgumentException("Usage: java GenerateUiColors.java <table.tsv> <IslandsDarkUiColors.kt> <client build>");
    }
    final List<String> lines = Files.readAllLines(Path.of(arguments[0]));
    if (lines.isEmpty()) throw new IllegalArgumentException("Empty table: " + arguments[0]);
    for (final String line : lines) {
      if (line.contains("$") || line.contains("\"")) throw new IllegalArgumentException("Can't go in a raw string: " + line);
    }
    final List<String> parts = new ArrayList<>();
    StringBuilder part = new StringBuilder();
    for (final String line : lines) {
      if (part.length() + line.length() + 1 > PART_BYTES) {
        parts.add(part.toString());
        part = new StringBuilder();
      }
      part.append(line).append('\n');
    }
    parts.add(part.toString());

    final StringBuilder kotlin = new StringBuilder();
    kotlin.append("// Generated by tools/ui-colors/GenerateUiColors.java from JetBrains Client ")
        .append(arguments[2]).append("'s UIManager with Islands Dark. Don't edit; regenerate (docs/lux-protocol.md).\n");
    kotlin.append("package io.github.safeuq.ideate.client.ui.theme\n\n");
    kotlin.append("/** The table, in parts that each fit in a class file's string constant. */\n");
    kotlin.append("internal val ISLANDS_DARK_UI_COLORS: List<String> =\n  listOf(");
    for (int index = 0; index < parts.size(); index++) kotlin.append(index == 0 ? "" : ", ").append("PART_").append(index + 1);
    kotlin.append(")\n");
    for (int index = 0; index < parts.size(); index++) {
      kotlin.append("\nprivate const val PART_").append(index + 1).append(" =\n  \"\"\"").append(parts.get(index)).append("\"\"\"\n");
    }
    Files.writeString(Path.of(arguments[1]), kotlin.toString());
  }
}
